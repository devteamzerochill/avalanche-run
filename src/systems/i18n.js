export const STRINGS = { en, es, zh };
export const LANGS = ['en', 'es', 'zh'];
export const LANG_NAMES = { auto: 'Auto', en: 'English', es: 'Español', zh: '中文' };

let current = 'en';

export function detectLang(pref) {
  if (pref && pref !== 'auto' && STRINGS[pref]) return pref;
  const nav = (typeof navigator !== 'undefined' && (navigator.language || '')) || 'en';
  const short = nav.toLowerCase().slice(0, 2);
  return STRINGS[short] ? short : 'en';
}

export function setLang(pref) {
  current = detectLang(pref);
  return current;
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  let s = STRINGS[current][key];
  if (s == null) s = en[key];
  if (s == null) return key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
